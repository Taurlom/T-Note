internal fun themeSpecOf(kind: ThemeKind): AppThemeSpec = when (kind) {
    ThemeKind.DARK -> DarkTheme
    ThemeKind.LIGHT -> LightTheme
    ThemeKind.OCEAN -> OceanTheme
    ThemeKind.FOREST -> ForestTheme
    ThemeKind.AUTUMN -> AutumnTheme
}
