package ru.taurlom.tnote.domain.notifications

/**
 * Планировщик задачи ежедневной сводки. Реализация — WorkManager
 * (data/notifications): задачи переживают перезагрузку, обновление
 * приложения и doze, не требуют разрешений и BOOT-ресиверов.
 *
 * [Mode] описывает, что делать с уже висящей задачей: у каждого места
 * вызова своя ситуация, и «одна политика на всё» ломает одну из них.
 * KEEP гасил бы самоперепланирование воркера (он видит «живую» задачу —
 * себя); REPLACE отменял бы задачу, которая сейчас бежит (процесс мог
 * быть поднят WorkManager'ом ради неё); APPEND плодил бы дубли при
 * каждом старте приложения. Поэтому режим выбирает вызывающий.
 */
interface ReminderScheduler {

    enum class Mode {
        /** Заменить висящую задачу новой: включение и смена времени в настройках. */
        RESCHEDULE,

        /**
         * Ставить только если ничего не висит: старт приложения «лечит»
         * цепочку, не трогая живую задачу — процесс мог быть поднят
         * самим WorkManager'ом ради бегущего воркера, и REPLACE убил бы его.
         */
        IF_IDLE,

        /**
         * Прицепить за текущей: финал воркера — он ставит себе смену на
         * завтра, не отменяя себя (REPLACE изнутри пометил бы его
         * «cancelled», хоть публикация уже случилась).
         */
        AFTER_CURRENT
    }

    /** Запланировать срабатывание сводки на [atEpochMillis]. */
    suspend fun scheduleNextDigest(atEpochMillis: Long, mode: Mode)

    /** Убрать запланированные задачи: напоминания выключили. */
    suspend fun cancelScheduledDigests()
}
